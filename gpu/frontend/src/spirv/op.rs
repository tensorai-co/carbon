/// Instructions that end a block.
pub const fn is_terminator(op: u16) -> bool {
    matches!(op, BRANCH | BRANCH_CONDITIONAL | SWITCH | KILL | RETURN | RETURN_VALUE | UNREACHABLE | TERMINATE_INVOCATION)
}

/// A name for error messages: the common ones by name, the rest by number.
pub fn name(op: u16) -> alloc::string::String {
    let known = match op {
        FUNCTION_CALL => "OpFunctionCall",
        EXT_INST => "OpExtInst",
        LOAD => "OpLoad",
        STORE => "OpStore",
        ACCESS_CHAIN => "OpAccessChain",
        PHI => "OpPhi",
        SWITCH => "OpSwitch",
        KILL => "OpKill",
        RETURN_VALUE => "OpReturnValue",
        UNREACHABLE => "OpUnreachable",
        TERMINATE_INVOCATION => "OpTerminateInvocation",
        IMAGE_SAMPLE_IMPLICIT_LOD => "OpImageSampleImplicitLod",
        IMAGE_SAMPLE_EXPLICIT_LOD => "OpImageSampleExplicitLod",
        _ => return alloc::format!("SPIR-V instruction {op}"),
    };
    known.into()
}

